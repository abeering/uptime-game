    // Bounded, disposable presentation experiment. Run in an isolated batch Editor;
    // never saves a scene/prefab, creates connections, or steps the simulation.
    public static class GeometryCapacityStudy
    {
        private const string Output = "Docs/research/geometry-capacity-v0";
        private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;
        private static string F(float value) => value.ToString("0.##", Invariant);
        private static float Setting(Object owner, string field) =>
            new SerializedObject(owner).FindProperty(field).floatValue;
        private static IdentityPresenter identity;
        private static LogicalPathPresenter presenter;
        private static float clearance;

        public static void Run()
        {
            if (!Application.isBatchMode)
                throw new InvalidOperationException("Use -batchmode in an isolated project copy; see the report.");
            var protectedFiles = Directory.GetFiles("Assets/Prefabs/Connections", "*", SearchOption.AllDirectories)
                .Concat(new[] { "Assets/Scenes/Connections.unity", "Assets/Scenes/GameScene.unity",
                    "Assets/Scenes/ABScene.unity" }).ToDictionary(p => p, Hash);
            EditorSceneManager.OpenScene("Assets/Scenes/Connections.unity");
            presenter = Object.FindFirstObjectByType<LogicalPathPresenter>();
            identity = Object.FindFirstObjectByType<IdentityPresenter>();
            clearance = Setting(identity, "pillToLineClearance");
            var preview = Object.FindFirstObjectByType<GeometryPreview>();
            preview.enabled = false;
            var canvas = presenter.GetComponentInParent<Canvas>();
            var cameraObject = new GameObject("Study capture camera", typeof(Camera));
            var camera = cameraObject.GetComponent<Camera>();
            var target = new RenderTexture(1920, 1080, 24);
            try
            {
                camera.orthographic = true;
                camera.orthographicSize = 5;
                camera.clearFlags = CameraClearFlags.SolidColor;
                camera.backgroundColor = new Color(0.028f, 0.075f, 0.09f);
                camera.cullingMask = ~0;
                camera.targetTexture = target;
                canvas.renderMode = RenderMode.ScreenSpaceCamera;
                canvas.worldCamera = camera;
                canvas.planeDistance = 1;
                canvas.additionalShaderChannels |= AdditionalCanvasShaderChannels.TexCoord1;
                Canvas.ForceUpdateCanvases();
                Require(Mathf.Abs(((RectTransform)canvas.transform).rect.width - 1920) < 0.1f,
                    "1920 reference canvas");
                Directory.CreateDirectory(Output);
                var nodes = Object.FindObjectsByType<NodeView>(FindObjectsSortMode.None)
                    .OrderBy(n => n.NodeId).ToArray();
                var links = Object.FindObjectsByType<PhysicalLinkView>(FindObjectsSortMode.None)
                    .OrderBy(l => l.LinkId).ToArray();
                foreach (var link in links) link.SendMessage("LateUpdate");
                Canvas.ForceUpdateCanvases();
                var data = new StringBuilder("# Geometry capacity V0 — measured data\n\n" +
                    "Generated by `GeometryCapacityStudy.Run`, Unity " + Application.unityVersion +
                    ". Units: reference UI pixels at 1920×1080. No simulation steps.\n\n");
                foreach (string name in new[] { "GameCanvas", "TerminalPanel", "NetworkPanel", "PhysicalTopology" })
                {
                    RectTransform rect = GameObject.Find(name).GetComponent<RectTransform>();
                    data.AppendLine($"- {name}: {F(rect.rect.width)} × {F(rect.rect.height)}");
                }
                data.AppendLine($"- Lines: max {F(presenter.MaxLineWidth)}, diagnostic min {F(presenter.MinLineWidth)}, min gap {F(presenter.MinLineGap)}");
                data.AppendLine($"- Pill: {identity.PillSize}, gap {F(identity.MinimumPillGap)}, step {F(identity.StaggerStep)}, inset {F(identity.EndInset)}, clearance {F(clearance)}");
                data.AppendLine("\n## Authored links\n\n|Link|Heading A→B (degrees)|Center distance|Visible center lane|Budget|Label offset|\n|---|---:|---:|---:|---:|---:|");
                foreach (var link in links)
                {
                    Rect a = EdgeGeometry.CardRect(link.NodeA, presenter.NetworkArea);
                    Rect b = EdgeGeometry.CardRect(link.NodeB, presenter.NetworkArea);
                    Vector2 d = (b.center - a.center).normalized;
                    float visible = Vector2.Distance(EdgeGeometry.CardEdge(a, d, 0), EdgeGeometry.CardEdge(b, -d, 0));
                    data.AppendLine($"|{link.LinkId}|{F(Mathf.Atan2(d.y, d.x) * Mathf.Rad2Deg)}|{F(Vector2.Distance(a.center, b.center))}|{F(visible)}|{F(link.BundleWidth(presenter.NetworkArea))}|{F(Setting(link, "labelOffset"))}|");
                }
                data.AppendLine("\n## Node contents, unchanged child layout\n\n" +
                    "Text preferred widths measured with the authored font/size. Bounds are relative to node center.\n\n" +
                    "|Scale|Node|Card|Heading rect|Heading preferred width incl. gap|LOAD rect|Track|Child rectangles outside card|\n|---|---|---|---|---:|---|---|---:|");
                Vector2 size = ((RectTransform)nodes[0].transform).rect.size;
                foreach (float scale in new[] { 1f, 0.8f, 0.65f })
                {
                    foreach (var node in nodes)
                    {
                        ((RectTransform)node.transform).sizeDelta = size * scale;
                        LayoutRebuilder.ForceRebuildLayoutImmediate((RectTransform)node.transform);
                    }
                    Canvas.ForceUpdateCanvases();
                    foreach (var node in nodes)
                    {
                        Rect card = EdgeGeometry.CardRect(node, presenter.NetworkArea);
                        var heading = node.transform.Find("NodeHeading").GetComponent<RectTransform>();
                        var load = (RectTransform)node.LoadBar.transform;
                        var track = load.Find("Load Track").GetComponent<RectTransform>();
                        var content = new[] { heading, load, track };
                        int outside = content.Count(r => !Contains(card, Bounds(r).Center - Bounds(r).HalfSize) ||
                            !Contains(card, Bounds(r).Center + Bounds(r).HalfSize));
                        float preferred = heading.GetComponentsInChildren<TMP_Text>().Sum(t => t.GetPreferredValues(t.text).x) +
                            heading.GetComponent<HorizontalLayoutGroup>().spacing;
                        data.AppendLine($"|{F(scale)}|{node.NodeId}|{F(card.width)} × {F(card.height)}|{RelativeRect(heading, card.center)}|{F(preferred)}|{RelativeRect(load, card.center)}|{F(track.rect.width)} × {F(track.rect.height)}|{outside}|");
                    }
                }
                foreach (var node in nodes) ((RectTransform)node.transform).sizeDelta = size;
                Canvas.ForceUpdateCanvases();

                var rows = new StringBuilder("size_scale,budget_scale,orientation,visible_length,count,budget,line_width,line_gap,stage,visible_min,visible_max,phases,ids_covered,below_min,bundle_fits,ends_covered\n");
                // Full required length/density cross only at baseline. Compact shapes use one
                // representative length; proportional budgets are a separate sensitivity test.
                foreach (float angle in new[] { 0f, 90f, 45f })
                    foreach (float length in new[] { 120f, 180f, 240f, 320f })
                        foreach (int count in new[] { 2, 4, 6, 8, 12 })
                            Case(rows, nodes[0], size, 1, 1, angle, length, count);
                foreach (float scale in new[] { 0.8f, 0.65f })
                    foreach (float angle in new[] { 0f, 90f, 45f })
                    {
                        foreach (int count in new[] { 2, 4, 6, 8, 12 })
                            Case(rows, nodes[0], size, scale, 1, angle, 180, count);
                        foreach (int count in new[] { 4, 8, 12 })
                            Case(rows, nodes[0], size, scale, scale, angle, 180, count);
                    }
                Case(rows, nodes[0], size, 1, 1, 0, 70, 2); // One unavailable control.
                File.WriteAllText(Path.Combine(Output, "link-cases.csv"), rows.ToString());

                data.AppendLine("\n## Local junction: independently solved edges, 180 px visible\n\n" +
                    "Counts are intersecting strip/marker pairs across the two links (not within one link). " +
                    "Strips cover the first 40 visible px at the shared node; markers use the production socket helper. " +
                    "This is a local collision diagnostic, not a complete placed topology.\n\n" +
                    "|Card scale|Headings|Lanes per link|Stages|Cross-link strip pairs|Cross-link socket bounds pairs|\n|---|---|---:|---|---:|---:|");
                var markerPrefab = AssetDatabase.LoadAssetAtPath<GameObject>("Assets/Prefabs/Connections/TerminalMarker.prefab");
                TerminalMarkerStyle socketStyle = markerPrefab.GetComponent<TerminalMarkerStyle>();
                foreach (float scale in new[] { 1f, 0.8f, 0.65f })
                    foreach (var angles in new[] { new[] { 45f, 90f }, new[] { 0f, 15f } })
                        foreach (int count in new[] { 4, 8 })
                        {
                            Rect card = new Rect(-size * scale * 0.5f, size * scale);
                            var layouts = angles.Select(a => Solve(nodes[0], size, scale, 1, a, 180, count)).ToArray();
                            var strips = new List<IdentityPacking.PillBounds[]>();
                            var markers = new List<IdentityPacking.PillBounds[]>();
                            for (int k = 0; k < 2; k++)
                            {
                                Vector2 d = Direction(angles[k]);
                                var layout = layouts[k];
                                strips.Add(Enumerable.Range(0, count).Select(i =>
                                {
                                    float offset = EdgeGeometry.Offset(i, count, layout.LineWidth, layout.LineGap);
                                    Vector2 edge = EdgeGeometry.CardEdge(card, d, offset);
                                    return new IdentityPacking.PillBounds(edge + d * 20, d, new Vector2(40, layout.LineWidth));
                                }).ToArray());
                                markers.Add(Enumerable.Range(0, count).Select(i =>
                                {
                                    float diameter = count > 1 ? Mathf.Max(12f,
                                        Mathf.Min(socketStyle.PreferredDiameter,
                                            layout.LineWidth + layout.LineGap - 2f)) :
                                        socketStyle.PreferredDiameter;
                                    Rect rect = LogicalPathView.TerminalSocketRect(card, d,
                                        EdgeGeometry.Offset(i, count, layout.LineWidth, layout.LineGap),
                                        diameter, socketStyle.BorderOutset);
                                    return new IdentityPacking.PillBounds(rect.center, Vector2.right, rect.size);
                                }).ToArray());
                            }
                            data.AppendLine($"|{F(scale)}|{F(angles[0])} / {F(angles[1])}|{count}|{layouts[0].Stage} / {layouts[1].Stage}|{Collisions(strips[0], strips[1])}|{Collisions(markers[0], markers[1])}|");
                        }
                File.WriteAllText(Path.Combine(Output, "measurements.md"), data.ToString());
                Capture(camera, target, nodes, links, size, 1, 4, "baseline-4.png");
                Capture(camera, target, nodes, links, size, 0.8f, 4, "compact-80-4.png");
                Capture(camera, target, nodes, links, new Vector2(260, size.y), 1, 4, "width-only-260-4.png");
                Capture(camera, target, nodes, links, size, 1, 12, "crowded-12.png");
                Debug.Log("GeometryCapacityStudy PASS: 108 link cases plus unavailable control, 12 local junction cases, content measurements, four 16:9 captures.");
            }
            finally
            {
                Object.DestroyImmediate(cameraObject);
                Object.DestroyImmediate(target);
                foreach (var file in protectedFiles)
                    Require(Hash(file.Key) == file.Value, "unchanged on disk: " + file.Key);
                // Discard all in-memory study changes; no SaveScene/SaveAssets call.
                EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
            }
        }

        private static Vector2 Direction(float angle) => new Vector2(Mathf.Cos(angle * Mathf.Deg2Rad), Mathf.Sin(angle * Mathf.Deg2Rad));
        private static IdentityPacking.Layout Solve(NodeView node, Vector2 originalSize, float scale,
            float budgetScale, float angle, float length, int count)
        {
            Vector2 d = Direction(angle);
            Rect a = new Rect(-originalSize * scale * 0.5f, originalSize * scale);
            float radius = Vector2.Dot(EdgeGeometry.CardEdge(a, d, 0), d);
            Rect b = new Rect(a.position + d * (length + 2 * radius), a.size);
            Vector2 start = EdgeGeometry.CardEdge(a, d, 0);
            Vector2 end = EdgeGeometry.CardEdge(b, -d, 0);
            // Retain the diagonal production label's 116×24 footprint and 80 px offset.
            // For H/V use the matching authored orientation (E1 is vertical, offset 100).
            Vector2 normal = new Vector2(-d.y, d.x);
            if (normal.y < 0) normal = -normal;
            var obstacles = new[] { new IdentityPacking.PillBounds(a.center, Vector2.right, a.size),
                new IdentityPacking.PillBounds(b.center, Vector2.right, b.size),
                new IdentityPacking.PillBounds((a.center + b.center) * 0.5f + normal * (angle == 90 ? 100 : 80), d, new Vector2(116, 24)) };
            return IdentityPacking.Solve(start, end, node.BundleWidthToward(d) * budgetScale, count,
                presenter.MaxLineWidth, presenter.MinLineWidth, presenter.MinLineGap, identity.PillSize,
                identity.MinimumPillGap, identity.StaggerStep, identity.EndInset, clearance, obstacles, a, b);
        }

        private static void Case(StringBuilder rows, NodeView node, Vector2 size, float scale,
            float budgetScale, float angle, float length, int count)
        {
            var layout = Solve(node, size, scale, budgetScale, angle, length, count);
            float budget = node.BundleWidthToward(Direction(angle)) * budgetScale;
            float occupied = count * layout.LineWidth + (count - 1) * layout.LineGap;
            var ids = new HashSet<int>(layout.Schedule.SelectMany(c => c).Select(p => p.LaneIndex));
            // Recheck actual solver invariants, without asserting that an intentionally
            // saturated case or uncovered attachment is a usable presentation.
            foreach (var phase in layout.Schedule)
                for (int i = 0; i < phase.Count; i++)
                    for (int j = 0; j < i; j++)
                        Require(!IdentityPacking.Intersects(phase[i].Bounds, phase[j].Bounds, identity.MinimumPillGap), "pill separation");
            bool covered = layout.Lanes.All(l =>
                Covered(new Rect(-size * scale * 0.5f, size * scale), l.Start, Direction(angle), l.Width));
            int min = layout.Schedule.Count == 0 ? 0 : layout.Schedule.Min(c => c.Count);
            int max = layout.Schedule.Count == 0 ? 0 : layout.Schedule.Max(c => c.Count);
            rows.AppendLine(string.Join(",", new[] { F(scale), F(budgetScale), F(angle), F(length), count.ToString(), F(budget),
                F(layout.LineWidth), F(layout.LineGap), layout.Stage.ToString(), min.ToString(), max.ToString(),
                layout.Schedule.Count.ToString(), ids.Count.ToString(), (layout.LineWidth < presenter.MinLineWidth).ToString(),
                (occupied <= budget + 0.02f).ToString(), covered.ToString() }));
        }

        private static void Capture(Camera camera, RenderTexture target, NodeView[] nodes,
            PhysicalLinkView[] links, Vector2 size, float scale, int count, string file)
        {
            foreach (var node in nodes) ((RectTransform)node.transform).sizeDelta = size * scale;
            Canvas.ForceUpdateCanvases();
            var graphics = new List<GameObject>();
            identity.BeginFrame();
            try
            {
                foreach (var link in links)
                {
                    var layout = identity.ResolveLayout(link, count, presenter.MaxLineWidth, presenter.MinLineWidth, presenter.MinLineGap);
                    var lines = new List<IdentityPresenter.LiveLine>();
                    for (int i = 0; i < count; i++)
                    {
                        var lane = layout.Lanes[i];
                        var graphic = Object.Instantiate(presenter.PathGraphicPrefab, presenter.PathLayer, false);
                        graphics.Add(graphic.gameObject);
                        // Same production path mesh and endpoints as GeometryPreview; fixed
                        // full establishment, no activity animation or simulated connections.
                        graphic.color = Color.HSVToRGB(0.44f + (i % 6) * 0.017f, 0.6f, 0.94f);
                        graphic.SetPath(new[] { lane.Start }, new[] { lane.End }, new[] { lane.Width }, 1);
                        lines.Add(new IdentityPresenter.LiveLine(((char)('a' + i)).ToString() + i % 10, lane.Start, lane.End,
                            lane.Start, lane.End, graphic.color, 1, lane.Width));
                    }
                    identity.PresentEdge(link, lines);
                    Debug.Log($"Study capture {file} {link.LinkId}: {layout.Stage}, {F(layout.LineWidth)}/{F(layout.LineGap)} width/gap, scheduled {layout.Schedule[0].Count}");
                }
                identity.EndFrame();
                Canvas.ForceUpdateCanvases();
                int shown = identity.GetComponentsInChildren<IdentityPillView>().Count(p => p.gameObject.activeInHierarchy);
                Debug.Log($"Study capture {file}: {shown} rendered pills across three links");
                camera.Render();
                RenderTexture previous = RenderTexture.active;
                Texture2D image = new Texture2D(1920, 1080, TextureFormat.RGB24, false);
                try
                {
                    RenderTexture.active = target;
                    image.ReadPixels(new Rect(0, 0, 1920, 1080), 0, 0);
                    image.Apply();
                    File.WriteAllBytes(Path.Combine(Output, file), image.EncodeToPNG());
                }
                finally { RenderTexture.active = previous; Object.DestroyImmediate(image); }
            }
            finally
            {
                identity.BeginFrame();
                identity.EndFrame();
                foreach (var graphic in graphics) Object.DestroyImmediate(graphic);
            }
        }

        private static IdentityPacking.PillBounds Bounds(RectTransform rect)
        {
            var corners = new Vector3[4];
            rect.GetWorldCorners(corners);
            Vector2 low = presenter.NetworkArea.InverseTransformPoint(corners[0]);
            Vector2 high = presenter.NetworkArea.InverseTransformPoint(corners[2]);
            return new IdentityPacking.PillBounds((low + high) * 0.5f, Vector2.right, high - low);
        }
        private static string RelativeRect(RectTransform rect, Vector2 center)
        {
            var bounds = Bounds(rect);
            Vector2 low = bounds.Center - bounds.HalfSize - center;
            return $"({F(low.x)}, {F(low.y)}) {F(bounds.HalfSize.x * 2)} × {F(bounds.HalfSize.y * 2)}";
        }
        private static bool Contains(Rect r, Vector2 p) => p.x >= r.xMin - 0.01f && p.x <= r.xMax + 0.01f && p.y >= r.yMin - 0.01f && p.y <= r.yMax + 0.01f;
        private static bool Covered(Rect card, Vector2 end, Vector2 direction, float width)
        {
            Vector2 half = new Vector2(-direction.y, direction.x) * (width * 0.5f);
            return Contains(card, end - half) && Contains(card, end + half);
        }
        private static int Collisions(IdentityPacking.PillBounds[] a, IdentityPacking.PillBounds[] b) =>
            a.Sum(x => b.Count(y => IdentityPacking.Intersects(x, y, 0)));
        private static string Hash(string path)
        {
            using (var sha = SHA256.Create()) return Convert.ToBase64String(sha.ComputeHash(File.ReadAllBytes(path)));
        }
        private static void Require(bool condition, string message)
        {
            if (!condition) throw new InvalidOperationException("GeometryCapacityStudy: " + message);
        }
    }
